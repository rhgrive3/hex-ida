import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'js/userscript/deployment-identity.generated.js');

export function deploymentCommit(cwd, env, { execFileSyncImpl = execFileSync } = {}) {
  const workersCommit = normalizeCommit(env.WORKERS_CI_COMMIT_SHA);
  try {
    const status = execFileSyncImpl('git', [
      'status', '--porcelain=v1', '--untracked-files=all', '--', '.',
      ':(exclude)js/userscript/deployment-identity.generated.js',
    ], {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    if (String(status || '').trim()) return null;
    const head = normalizeCommit(execFileSyncImpl('git', ['rev-parse', 'HEAD'], {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }));
    if (!head) return null;
    return workersCommit ? (workersCommit === head ? workersCommit : null) : head;
  } catch {
    return null;
  }
}

export function normalizeCommit(value) {
  const text = String(value || '').trim().toLowerCase();
  return /^[0-9a-f]{40}$/.test(text) ? text : null;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const commit = deploymentCommit(root, process.env);
  await writeFile(out, `// Generated by scripts/write-deployment-identity.mjs during the Workers build.\nexport const DEPLOYMENT_COMMIT=${JSON.stringify(commit)};\n`);
  console.log(`deployment source commit ${commit || 'unavailable'}`);
}
