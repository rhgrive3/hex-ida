import { execFileSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { open, rename, rm } from 'node:fs/promises';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'js/userscript/deployment-identity.generated.js');

export function deploymentCommit(cwd, env, { execFileSyncImpl = execFileSync } = {}) {
  const workersCommit = normalizeCommit(env.WORKERS_CI_COMMIT_SHA);
  try {
    const status = execFileSyncImpl('git', [
      'status', '--porcelain=v1', '--untracked-files=all', '--', '.',
      ':(exclude)js/userscript/deployment-identity.generated.js',
    ], {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    if (String(status || '').trim()) return null;
    const head = normalizeCommit(execFileSyncImpl('git', ['rev-parse', 'HEAD'], {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }));
    if (!head) return null;
    return workersCommit ? (workersCommit === head ? workersCommit : null) : head;
  } catch {
    return null;
  }
}

export function normalizeCommit(value) {
  const text = String(value || '').trim().toLowerCase();
  return /^[0-9a-f]{40}$/.test(text) ? text : null;
}

export async function publishDeploymentIdentity(outputPath, content, {
  openImpl = open,
  renameImpl = rename,
  rmImpl = rm,
  randomUUIDImpl = randomUUID,
} = {}) {
  const target = resolve(outputPath);
  const temp = resolve(dirname(target), `.${basename(target)}.tmp-${process.pid}-${randomUUIDImpl()}`);
  let handle = null;
  let primaryError = null;

  try {
    handle = await openImpl(temp, 'wx', 0o600);
    await handle.writeFile(content);
    await handle.close();
    handle = null;

    // rename() replaces the directory entry itself. Unlike writeFile(target),
    // it does not follow an existing final-leaf symlink.
    await renameImpl(temp, target);
    return;
  } catch (error) {
    primaryError = error;
  }

  if (handle) {
    try {
      await handle.close();
    } catch (closeError) {
      if (primaryError?.cause == null) primaryError.cause = closeError;
      primaryError.cleanupError = closeError;
    }
  }
  try {
    await rmImpl(temp, { force: true });
  } catch (cleanupError) {
    if (primaryError?.cause == null) primaryError.cause = cleanupError;
    primaryError.cleanupError ??= cleanupError;
  }
  throw primaryError;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const commit = deploymentCommit(root, process.env);
  await publishDeploymentIdentity(
    out,
    `// Generated by scripts/write-deployment-identity.mjs during the Workers build.\nexport const DEPLOYMENT_COMMIT=${JSON.stringify(commit)};\n`,
  );
  console.log(`deployment source commit ${commit || 'unavailable'}`);
}
